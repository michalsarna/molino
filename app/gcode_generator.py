import math
import numpy as np


# Minimum Z increment — matches typical CNC step resolution.
# Depths are quantized to this grid so programmed Z = executed Z.
Z_STEP = 0.01  # mm


def _q(z_mm: float) -> float:
    """Round a positive depth value to the nearest Z_STEP."""
    return round(z_mm / Z_STEP) * Z_STEP


def generate_gcode(heightmap: np.ndarray, params: dict) -> str:
    rows, cols = heightmap.shape

    width_mm       = float(params.get("width_mm", 100.0))
    height_mm      = float(params.get("height_mm", 100.0))
    cut_depth_mm   = float(params.get("cut_depth", 3.0))
    safe_height    = float(params.get("safe_height", 5.0))
    spindle_speed  = int(params.get("spindle_speed", 12000))
    feed_rate      = float(params.get("feed_rate", 1000.0))
    plunge_rate    = float(params.get("plunge_rate", 300.0))
    bit_type       = params.get("bit_type", "vbit")
    bit_diameter   = float(params.get("bit_diameter", 3.175))
    tip_angle      = float(params.get("tip_angle", 60.0))
    depth_per_pass = float(params.get("depth_per_pass", cut_depth_mm))
    if depth_per_pass <= 0 or depth_per_pass >= cut_depth_mm:
        depth_per_pass = cut_depth_mm
    num_passes = math.ceil(cut_depth_mm / depth_per_pass)

    imperial = params.get("units", "metric") == "imperial"
    if imperial:
        f          = 1.0 / 25.4
        unit_label = "in"
        unit_cmd   = "G20"
    else:
        f          = 1.0
        unit_label = "mm"
        unit_cmd   = "G21"

    x_step = width_mm  / max(cols - 1, 1)
    y_step = height_mm / max(rows - 1, 1)

    # Pre-compute quantized target depths (mm, positive) for every pixel once
    raw_depths = heightmap * cut_depth_mm          # 0 … cut_depth_mm
    q_depths   = np.round(raw_depths / Z_STEP) * Z_STEP  # quantised

    lines = [
        "; ============================================================",
        "; Generated by Molino v0.14",
        f"; Physical size:  {width_mm * f:.4f} x {height_mm * f:.4f} {unit_label}",
        f"; Max cut depth:  {cut_depth_mm * f:.4f} {unit_label}",
        f"; Depth per pass: {depth_per_pass * f:.4f} {unit_label} "
            f"({num_passes} pass{'es' if num_passes > 1 else ''})",
        f"; Z step:         {Z_STEP * f:.4f} {unit_label}",
        f"; Step over:      {x_step * f:.5f} {unit_label} (X), "
            f"{y_step * f:.5f} {unit_label} (Y)",
        f"; Spindle:        {spindle_speed} RPM",
        f"; Feed rate:      {feed_rate * f:.4f} {unit_label}/min",
        f"; Plunge rate:    {plunge_rate * f:.4f} {unit_label}/min",
    ]

    if bit_type == "vbit":
        lines.append(
            f"; Tool: V-bit {tip_angle}° included angle, "
            f"{bit_diameter * f:.4f} {unit_label} diameter"
        )
    else:
        lines.append(
            f"; Tool: End mill {bit_diameter * f:.4f} {unit_label} diameter"
        )

    lines += [
        "; ============================================================",
        "",
        f"{unit_cmd}        ; {unit_label} units",
        "G90        ; absolute positioning",
        "G17        ; XY plane",
        f"G0 Z{safe_height * f:.4f}   ; move to safe height",
        "G0 X0 Y0   ; move to origin",
        "T1 M6      ; select tool 1 (remove if no ATC)",
        f"M3 S{spindle_speed}   ; start spindle",
        "G4 P2      ; spindle warm-up 2 s",
        "",
    ]

    for pass_num in range(1, num_passes + 1):
        pass_max_q  = _q(min(pass_num * depth_per_pass, cut_depth_mm))
        prev_max_q  = _q((pass_num - 1) * depth_per_pass) if pass_num > 1 else 0.0

        if num_passes > 1:
            lines.append(
                f"; --- Pass {pass_num}/{num_passes}  "
                f"depth {prev_max_q * f:.4f} → {pass_max_q * f:.4f} {unit_label} ---"
            )

        for row_idx in range(rows):
            # Skip rows where every pixel was already cut to its final depth
            # in a previous pass — nothing new to remove.
            if pass_num > 1 and float(np.max(q_depths[row_idx])) <= prev_max_q:
                continue

            y       = row_idx * y_step
            forward = row_idx % 2 == 0
            first_col = 0 if forward else cols - 1

            start_x     = first_col * x_step
            start_depth = min(float(q_depths[row_idx, first_col]), pass_max_q)
            start_z     = -start_depth

            lines.append(f"G0 Z{safe_height * f:.4f}")
            lines.append(f"G0 X{start_x * f:.4f} Y{y * f:.4f}")
            lines.append(f"G1 Z{start_z * f:.4f} F{plunge_rate * f:.4f}")

            rest    = range(1, cols) if forward else range(cols - 2, -1, -1)
            prev_z  = start_z

            for i, col_idx in enumerate(rest):
                x     = col_idx * x_step
                depth = min(float(q_depths[row_idx, col_idx]), pass_max_q)
                z     = -depth
                feed_suffix = f" F{feed_rate * f:.4f}" if i == 0 else ""

                if abs(z - prev_z) >= Z_STEP:
                    lines.append(f"G1 X{x * f:.4f} Z{z * f:.4f}{feed_suffix}")
                    prev_z = z
                else:
                    lines.append(f"G1 X{x * f:.4f}{feed_suffix}")

    lines += [
        "",
        f"G0 Z{safe_height * f:.4f}   ; lift to safe height",
        "G0 X0 Y0   ; return to origin",
        "M5         ; stop spindle",
        "M2         ; end program",
    ]

    return "\n".join(lines)
